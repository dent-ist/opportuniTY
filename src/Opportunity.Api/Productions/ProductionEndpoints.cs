    internal static async Task<IResult> LookupAsync(
        string workspaceId, string? number, string? documentId, HttpContext context, ProductionService service, CancellationToken cancellationToken)
    {
        _ = workspaceId;
        if (context.GetWorkspaceAccess() is not { } access)
        {
            return Problems.NotFound();
        }

        Guid? document = null;
        if (string.IsNullOrWhiteSpace(number) == string.IsNullOrWhiteSpace(documentId)
            || (documentId is not null && !Guid.TryParse(documentId, out _))
            || (number is not null && number.Trim().Length > 100))
        {
            return Problems.Validation(new Dictionary<string, string[]>
            {
                ["number"] = ["Give either a Bates number (at most 100 characters) or a documentId."],
            });
        }

        if (documentId is not null)
        {
            document = Guid.Parse(documentId);
        }

        var (matches, restricted) = await service.LookupAsync(access.Principal, access.WorkspaceId, number, document, cancellationToken).ConfigureAwait(false);
        return TypedResults.Ok(new BatesLookupResource(
            [.. matches.Select(m => new BatesLookupMatch(m.ProductionId, m.ProductionName, m.ProductionVersion, Status(m.ProductionStatus), m.DocumentId,
                m.ControlNumber, m.ProdBegBates, m.ProdEndBates, m.ProdBegAttach, m.ProdEndAttach))],
            new TotalCount(matches.Count, TotalRelation.Eq),
            restricted));
    }

    private sealed record FreezeResult(Guid? SnapshotId, IResult? Problem);

    /// <summary>Freezes a saved search the caller can see into a Production frozen set, as <c>POST …/snapshots</c> does.</summary>
    private static async Task<FreezeResult> FreezeSavedSearchAsync(
        HttpContext context, Application.Authorization.SecurityPrincipal principal, Guid workspaceId, Guid savedSearchId, string? name,
        CancellationToken cancellationToken)
    {
        var services = context.RequestServices;
        if (services.GetService<ISavedSearchQueries>() is not { } savedSearches
            || await savedSearches.FindForRunAsync(principal, workspaceId, savedSearchId, cancellationToken).ConfigureAwait(false) is not { } saved)
        {
            return new FreezeResult(null, Problems.NotFound("No such saved search."));
        }

        var session = Guid.TryParse(context.User.FindFirst(OpportunityClaimTypes.SessionId)?.Value, out var sid) ? sid : (Guid?)null;
        var snapshots = services.GetRequiredService<DocumentSetSnapshotService>();
        var outcome = await snapshots.CreateAsync(new SearchCaller(principal, workspaceId, session), new SnapshotCreateRequest(
            SnapshotPurpose.Production,
            string.IsNullOrWhiteSpace(name) ? null : name.Trim(),
            $"{SavedSearchQuerySyntax.FieldName}:{savedSearchId:D}",
            Expansion: saved.Expansion), cancellationToken).ConfigureAwait(false);
        switch (outcome.Status)
        {
            case SnapshotCreateStatus.Ready:
                return new FreezeResult(outcome.Snapshot!.SnapshotId, null);
            case SnapshotCreateStatus.Accepted:
                services.GetService<Snapshots.SnapshotMaterializationSignal>()?.Nudge(workspaceId, outcome.Snapshot!.SnapshotId);
                return new FreezeResult(outcome.Snapshot!.SnapshotId, null);
            case SnapshotCreateStatus.InvalidRequest or SnapshotCreateStatus.InvalidQuery:
                return new FreezeResult(null, Problems.Validation(new Dictionary<string, string[]>
                {
                    ["savedSearchId"] = ["The saved search cannot be run; open it to see why."],
                }));
            case SnapshotCreateStatus.Forbidden:
                return new FreezeResult(null, Problems.Create(StatusCodes.Status403Forbidden, ProblemCodes.Forbidden, "You do not have permission for this operation."));
            case SnapshotCreateStatus.TooLarge:
                return new FreezeResult(null, Problems.Create(StatusCodes.Status422UnprocessableEntity, ProblemCodes.UnprocessableContent,
                    "The saved search selects more documents than a frozen set may hold."));
            case SnapshotCreateStatus.Failed:
                return new FreezeResult(null, Problems.Create(StatusCodes.Status503ServiceUnavailable, ProblemCodes.ServiceUnavailable,
                    "The selection changed while it was being frozen; try again."));
            default:
                return new FreezeResult(null, Problems.NotFound("No such saved search."));
        }
    }

    private static async Task<ProductionRecord?> CurrentAsync(HttpContext context, string productionId, IProductionStore productions, CancellationToken cancellationToken) =>
        context.GetWorkspaceAccess() is { } access && Guid.TryParse(productionId, out var id)
            ? await productions.GetAsync(access.WorkspaceId, id, cancellationToken).ConfigureAwait(false)
            : null;

    private static async Task<IResult> ResultAsync(HttpContext context, ProductionOutcome outcome, IJobRepository jobs, CancellationToken cancellationToken)
    {
        if (outcome.Status != ProductionOutcomeStatus.Ok)
        {
            return Problem(outcome);
        }

        SetETag(context, outcome.Production!);
        return TypedResults.Ok(await ResourceAsync(outcome.Production!, jobs, cancellationToken).ConfigureAwait(false));
    }

    private static IResult Problem(ProductionOutcome outcome) => outcome.Status switch
    {
        ProductionOutcomeStatus.Invalid => Problems.Validation(outcome.Errors!.ToDictionary()),
        ProductionOutcomeStatus.NotFound => Problems.NotFound(NotFoundDetail),
        ProductionOutcomeStatus.VersionConflict => Problems.Create(StatusCodes.Status412PreconditionFailed, ProblemCodes.VersionConflict,
            "The production was modified since it was read."),
        ProductionOutcomeStatus.BatesConflict => TypedResults.Problem(
            statusCode: StatusCodes.Status409Conflict,
            detail: outcome.Reason,
            type: ProblemCodes.TypeFor(ProblemCodes.Conflict),
            extensions: new Dictionary<string, object?> { [Problems.CodeExtension] = ProblemCodes.Conflict, ["reason"] = "BATES_OVERLAP" }),
        ProductionOutcomeStatus.PrivilegeWithheld => TypedResults.Problem(
            statusCode: StatusCodes.Status409Conflict,
            title: "Documents are withheld for privilege",
            detail: outcome.Reason,
            type: ProblemCodes.TypeFor(ProblemCodes.Conflict),
            extensions: new Dictionary<string, object?> { [Problems.CodeExtension] = ProblemCodes.Conflict, ["reason"] = "PRIVILEGE_WITHHELD" }),
        ProductionOutcomeStatus.PrivilegeConflicts => TypedResults.Problem(
            statusCode: StatusCodes.Status409Conflict,
            title: "Unresolved privilege conflicts",
            detail: outcome.Reason,
            type: ProblemCodes.TypeFor(ProblemCodes.Conflict),
            extensions: new Dictionary<string, object?> { [Problems.CodeExtension] = ProblemCodes.Conflict, ["reason"] = "PRIVILEGE_CONFLICTS" }),
        ProductionOutcomeStatus.Forbidden => Problems.Create(StatusCodes.Status403Forbidden, ProblemCodes.Forbidden,
            outcome.Reason ?? "You do not have permission for this operation."),
        _ => Problems.Create(StatusCodes.Status409Conflict, ProblemCodes.Conflict, outcome.Reason ?? "The production's state does not allow this."),
    };

    private static void SetETag(HttpContext context, ProductionRecord production) =>
        context.Response.Headers.ETag = EntityTags.ForVersion(production.RowVersion);

    internal static async Task<ProductionResource> ResourceAsync(ProductionRecord production, IJobRepository jobs, CancellationToken cancellationToken)
    {
        var job = production.BatesJobId is { } jobId ? await jobs.GetAsync(production.WorkspaceId, jobId, cancellationToken).ConfigureAwait(false) : null;
        return ToResource(production, job);
    }

    internal static ProductionResource ToResource(ProductionRecord production, JobInfo? job)
    {
        var format = new BatesFormat(production.BatesPrefix, production.BatesPadding, production.BatesSuffix, BatesNumberingLevel.Page);
        return new ProductionResource(
            production.ProductionId,
            production.WorkspaceId,
            production.LineageId,
            production.Version,
            production.Name,
            production.SnapshotId,
            Status(production.Status),
            ProductionSpecificationRules.Deserialize(production.SpecificationJson),
            Convert.ToHexStringLower(production.SpecificationSha256),
            new ProductionBatesResource(
                Enum.Parse<BatesAllocationStateResource>(production.BatesState.ToString()),
                production.BatesReason,
                production.BatesFirst is { } f ? format.Format(f) : null,
                production.BatesLast is { } l && l >= 1 ? format.Format(l) : null,
                production.BatesFirst,
                production.BatesLast,
                production.BatesDocuments,
                production.BatesUnits,
                production.AssignmentsSha256 is { } a ? Convert.ToHexStringLower(a) : null,
                BatesIntegrityReport.FromJson(production.IntegrityJson) is { } integrity ? Integrity(integrity) : null),
            production.Manifest,
            production.ManifestSha256 is { } m ? Convert.ToHexStringLower(m) : null,
            production.CreatedBy,
            production.CreatedAt,
            production.ModifiedAt,
            production.FinalizedAt,
            production.VoidedAt,
            production.VoidReason,
            production.DiscardedAt,
            job is null ? null : JobEndpoints.ToResource(job));
    }

    private static ProductionIntegrityResource Integrity(BatesIntegrityReport report) => new(
        report.Passed, report.Documents, report.Numbers, report.Placeholders, report.NativeSlipSheets, report.Gaps, report.Problems);

    private static ProductionStatusResource Status(ProductionStatus status) => Enum.Parse<ProductionStatusResource>(status.ToString());
}

public static class ProductionEndpointRegistration
{
    /// <summary>The production API with its stores (the snapshot service comes with the snapshot endpoints).</summary>
    public static IServiceCollection AddProductionEndpoints(this IServiceCollection services)
    {
        ArgumentNullException.ThrowIfNull(services);
        services.AddPostgresProductionStore();
        services.AddPostgresSnapshotStore();
        services.TryAddSingleton<IJobRepository, JobRepository>();
        services.TryAddSingleton<IFieldCatalogRepository, FieldCatalogRepository>();
        services.TryAddSingleton<IFieldAccessFilter, UnrestrictedFieldAccess>();
        services.AddProductionService();
        services.AddSingleton<IApiEndpointModule, ProductionEndpoints>();
        return services;
    }
}
