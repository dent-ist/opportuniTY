    internal static async Task<IResult> CreateAsync(
        string workspaceId, CreateProductionRequest request, HttpContext context, ProductionService service, IJobRepository jobs,
        CancellationToken cancellationToken)
    {
        _ = workspaceId;
        if (context.GetWorkspaceAccess() is not { } access)
        {
            return Problems.NotFound();
        }

        if (request is null)
        {
            return Problems.Validation(new Dictionary<string, string[]> { ["body"] = ["Send the production request."] });
        }

        var sources = (request.SnapshotId is null ? 0 : 1) + (request.SavedSearchId is null ? 0 : 1) + (request.PreviousVersionId is null ? 0 : 1);
        if (sources != 1)
        {
            return Problems.Validation(new Dictionary<string, string[]>
            {
                ["snapshotId"] = ["Give exactly one of snapshotId, savedSearchId and previousVersionId."],
            });
        }

        var snapshotId = request.SnapshotId;
        if (request.SavedSearchId is { } savedSearchId)
        {
            switch (await FreezeSavedSearchAsync(context, access.Principal, access.WorkspaceId, savedSearchId, request.Name, cancellationToken).ConfigureAwait(false))
            {
                case { Problem: { } problem }:
                    return problem;
                case { SnapshotId: { } frozen }:
                    snapshotId = frozen;
                    break;
            }
        }

        var outcome = await service.CreateAsync(access.Principal, access.WorkspaceId, request, snapshotId, cancellationToken).ConfigureAwait(false);
        if (outcome.Status != ProductionOutcomeStatus.Ok)
        {
            return Problem(outcome);
        }

        SetETag(context, outcome.Production!);
        return TypedResults.Created(
            $"{ApiRoutes.V1Prefix}/workspaces/{access.WorkspaceId}{ProductionsPath}/{outcome.Production!.ProductionId}",
            await ResourceAsync(outcome.Production, jobs, cancellationToken).ConfigureAwait(false));
    }

    internal static async Task<IResult> ListAsync(
        string workspaceId, [AsParameters] PageQuery page, HttpContext context, IProductionStore productions, IJobRepository jobs,
        CancellationToken cancellationToken)
    {
        _ = workspaceId;
        if (context.GetWorkspaceAccess() is not { } access)
        {
            return Problems.NotFound();
        }

        if (page.Validate() is { } invalid)
        {
            return invalid;
        }

        ProductionListCursor? after = null;
        if (page.Cursor is { } cursor)
        {
            if (PageCursor.Decode(cursor, access.Principal.UserId, access.WorkspaceId, 2) is not [var ticks, var id]
                || !long.TryParse(ticks, NumberStyles.None, CultureInfo.InvariantCulture, out var t) || !Guid.TryParse(id, out var productionId))
            {
                return PageCursor.Invalid();
            }

            after = new ProductionListCursor(new DateTimeOffset(t, TimeSpan.Zero), productionId);
        }

        var limit = page.EffectiveLimit;
        var records = await productions.ListAsync(access.WorkspaceId, after, limit + 1, cancellationToken).ConfigureAwait(false);
        var items = new List<ProductionResource>();
        foreach (var record in records.Take(limit))
        {
            items.Add(await ResourceAsync(record, jobs, cancellationToken).ConfigureAwait(false));
        }

        var next = records.Count > limit
            ? PageCursor.Encode(access.Principal.UserId, access.WorkspaceId,
                records[limit - 1].CreatedAt.UtcTicks.ToString(CultureInfo.InvariantCulture), records[limit - 1].ProductionId.ToString("N"))
            : null;
        return TypedResults.Ok(new CursorPage<ProductionResource>(items, next,
            new TotalCount(items.Count, next is null && after is null ? TotalRelation.Eq : TotalRelation.Gte)));
    }

