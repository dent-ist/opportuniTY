/// <summary>
/// Productions (E12-T02, E12-T03): a frozen set plus a versioned specification, Bates numbers allocated by a job, and
/// finalization that freezes everything into a manifest. Every route needs <c>Production.Create</c>; finalizing and
/// voiding need <c>Production.Finalize</c>. Productions are shared by everyone holding <c>Production.Create</c> in the
/// workspace; listings of their documents leave out documents the caller may not view (Q-52). The volume itself (images,
/// natives, text, load files) is generated by E12-T05; its UI is E12-T08.
/// </summary>
public sealed class ProductionEndpoints : IApiEndpointModule
