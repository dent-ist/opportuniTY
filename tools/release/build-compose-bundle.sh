#!/usr/bin/env bash
# Builds the Compose release bundle opportunity-compose-vX.Y.Z.tgz (E01-T06): the Compose profile of the release
# commit with every image pinned by digest - opportuniTY's own images through a generated compose.images.yaml, the
# third-party services through versions.env - plus .env.example, the compatibility matrix, the changelog, the
# third-party NOTICE and SHA256SUMS. The archive is reproducible (sorted, fixed owner and mtime = commit time).
#
#   tools/release/build-compose-bundle.sh --version X.Y.Z --images images.env --compatibility-json FILE
#       --compatibility-md FILE --notice FILE [--changelog CHANGELOG.md] [--ref HEAD] [--output-dir dist] [--verify]
#
# images.env holds one line per opportuniTY image, `<name>=<registry/repository>@sha256:<digest>`, for api, worker,
# migrator and web (written by the release workflow from the pushed tags). --verify renders the bundle's Compose
# configuration with `docker compose config` and fails unless every image is referenced by digest.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"

version="" images="" compat_json="" compat_md="" notice="" changelog="$root/CHANGELOG.md" ref="HEAD"
output_dir="$root/dist" verify=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --version) version="${2#v}"; shift 2 ;;
    --images) images="$2"; shift 2 ;;
    --compatibility-json) compat_json="$2"; shift 2 ;;
    --compatibility-md) compat_md="$2"; shift 2 ;;
    --notice) notice="$2"; shift 2 ;;
    --changelog) changelog="$2"; shift 2 ;;
    --ref) ref="$2"; shift 2 ;;
    --output-dir) output_dir="$2"; shift 2 ;;
    --verify) verify=1; shift ;;
    -h|--help) sed -n '2,13p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
die() { echo "error: $*" >&2; exit 1; }
[[ "$version" =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z.-]+)?$ ]] \
  || die "--version must be SemVer X.Y.Z (got '$version')"
for f in "$images" "$compat_json" "$compat_md" "$notice"; do
  [[ -n "$f" && -f "$f" ]] || die "missing input file '${f}' (see --help)"
done

declare -A digest_ref
while IFS='=' read -r name value; do
  [[ -z "$name" || "$name" == \#* ]] && continue
  [[ "$value" =~ ^[a-z0-9./_-]+@sha256:[0-9a-f]{64}$ ]] || die "$images: '$name=$value' is not <repository>@sha256:<digest>"
  digest_ref[$name]="$value"
done < "$images"
for name in migrator api worker web; do
  [[ -n "${digest_ref[$name]:-}" ]] || die "$images has no digest for '$name'"
done

name="opportunity-compose-v$version"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
stage="$work/$name"
mkdir -p "$stage" "$output_dir"

# The tracked Compose profile of the release commit (no .env, no local overrides, no import share).
git -C "$root" archive --format=tar "$ref" versions.env LICENSE deploy/docker-compose | tar -x -C "$stage"
compose_dir="$stage/deploy/docker-compose"

# opportuniTY images by digest. Replaces the tag-based overlay of the developer profile in the bundle only.
image_line() { # <service> <name>: repository:X.Y.Z@sha256:..., the tag for people, the digest for Docker
  local repo="${digest_ref[$2]%@*}" digest="${digest_ref[$2]#*@}"
  printf '  %s:\n    <<: *published\n    image: %s:%s@%s\n' "$1" "$repo" "$version" "$digest"
}
{
  echo "# opportuniTY $version: the release images, pinned by digest (generated by tools/release/build-compose-bundle.sh)."
  echo "# Used by ./opportunity.sh --images ghcr ... (OPPORTUNITY_IMAGE_TAG in .env.example names the release)."
  echo "# Verify a digest: docs/ci.md#verify-a-published-image-operators."
  echo "x-published: &published"
  echo "  build: !reset null"
  echo "  pull_policy: missing"
  echo
  echo "services:"
  image_line migrator migrator
  image_line api api
  image_line worker worker
  image_line web web
} > "$compose_dir/compose.images.yaml"

{
  echo
  echo "# --- Release bundle $version (generated) ---------------------------------------------------------------------"
  echo "# Selects the published release images of compose.images.yaml (pinned by digest). Start with:"
  echo "#   OPPORTUNITY_IMAGES=ghcr ./opportunity.sh up"
  echo "OPPORTUNITY_IMAGE_TAG=$version"
} >> "$compose_dir/.env.example"

cp "$images" "$stage/images.env"
cp "$compat_json" "$stage/compatibility.json"
cp "$compat_md" "$stage/COMPATIBILITY.md"
cp "$notice" "$stage/THIRD-PARTY-NOTICES.md"
if [[ -f "$changelog" ]]; then
  # This release's section only: from its heading to the next release heading.
  awk -v v="$version" '
    /^## / { if (found) exit; if (index($0, "[" v "]") || index($0, " " v " ") || $0 ~ (" " v "$")) found = 1 }
    found { print }' "$changelog" > "$stage/CHANGELOG.md"
  [[ -s "$stage/CHANGELOG.md" ]] || cp "$changelog" "$stage/CHANGELOG.md"
fi

cat > "$stage/README.md" <<EOF
# opportuniTY $version - Docker Compose bundle

Everything needed to run opportuniTY $version with Docker Compose. Every image is pinned by digest: opportuniTY's own
images in \`deploy/docker-compose/compose.images.yaml\`, the third-party services in \`versions.env\`.

| File | Contents |
|---|---|
| \`deploy/docker-compose/\` | Compose profile, \`.env.example\`, \`opportunity.sh\` helper and its README |
| \`images.env\` | The release image digests |
| \`COMPATIBILITY.md\`, \`compatibility.json\` | Database schema version, search projection generation, message contract versions |
| \`CHANGELOG.md\` | Changes in this release |
| \`THIRD-PARTY-NOTICES.md\` | Third-party licenses |
| \`SHA256SUMS\` | Checksums of every file in this bundle |

## Install

\`\`\`sh
sha256sum -c SHA256SUMS
cd deploy/docker-compose
OPPORTUNITY_IMAGES=ghcr ./opportunity.sh up     # creates .env with random secrets, migrates, starts, waits
\`\`\`

## Upgrade from the previous release

Read \`COMPATIBILITY.md\` (supported upgrade source) and \`CHANGELOG.md\` first, and take a backup
(docs/architecture/restore-consistency.md). Then unpack this bundle next to the old one, copy the old
\`deploy/docker-compose/.env\` into the new directory, and run \`OPPORTUNITY_IMAGES=ghcr ./opportunity.sh up\`
there: the migrator upgrades the schema before the API and workers start. Data volumes are kept, because the Compose
project name stays the same.
EOF

if [[ $verify -eq 1 ]]; then
  cp "$compose_dir/.env.example" "$compose_dir/.env"
  sed -i -E 's/^([A-Z0-9_]+(PASSWORD|SECRET_KEY))=$/\1=verify-only-value-0123456789abcdef01/' "$compose_dir/.env"
  rendered="$(OPPORTUNITY_IMAGES=ghcr "$compose_dir/opportunity.sh" compose --profile '*' config --images)"
  rm -f "$compose_dir/.env"
  rm -rf "$compose_dir/import-share"
  unpinned="$(grep -v '@sha256:[0-9a-f]\{64\}$' <<<"$rendered" || true)"
  [[ -z "$unpinned" ]] || die "images not pinned by digest in the bundle: $unpinned"
  echo "verified: $(wc -l <<<"$rendered") images, all pinned by digest"
  while IFS= read -r line; do echo "  $line"; done <<<"$rendered"
fi

# Reproducible: fixed order, owner and mtime (the release commit's time); gzip without a timestamp.
epoch="$(git -C "$root" log -1 --format=%ct "$ref")"
(cd "$stage" && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 sha256sum > "$work/SHA256SUMS")
mv "$work/SHA256SUMS" "$stage/SHA256SUMS"

archive="$output_dir/$name.tgz"
tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="@$epoch" --format=gnu -C "$work" -cf - "$name" \
  | gzip -n -9 > "$archive"
echo "$archive ($(du -h "$archive" | cut -f1))"
